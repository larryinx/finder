"""StagedPlaybook — a 3-stage Experience backend (FIND / VERIFY / DECIDE).

Successor to ``tactic_playbook``. The analyses in
``docs/stage2/analysis/gptoss/*`` showed the old 3-tactic design
(A=exact-anchor / B=fingerprint / C=candidate-verify) was wrong for the
**dense** qwen3-8b retriever in two ways:

1. TACTIC_A told the agent to quote / shard ("short, quoted, high
   precision"), but quoting is inert on a dense retriever and shard
   chains fragment the sentence embedding — gpt-oss faithfully copied
   that and regressed (shard-query rate 44%→67%).
2. The genuinely decisive lessons (when to STOP searching and commit,
   anti-fame drift, two-hop bridge pivots) had nowhere to live — the
   reflector was prompt-locked to "QUERY DESIGN only" and every section
   was a query template. qwen36's +21.9pp came almost entirely from
   such *directive* lessons stated as plain imperatives.

StagedPlaybook fixes both at the source — the section list and the
hardcoded per-section preamble (``desc``) are what ``render()`` injects
into the agent prompt, so the corrected guidance reaches the agent in
BOTH training-time eval (``experience.render()``) and standalone
``eval_experience.py`` (which injects this file's text verbatim).

Three FIXED stages, in retrieval order:

    ## FIND — anchored constraint fingerprint
    (one coherent natural-language sentence; NO quotes / boolean / shards)

    [F-001] :: **Task**: ...
             **Pre-search state**: ...
             **Good query**: `...` — ...
             **Bad query**: `...` — ...
             **Caveat**: ...

    ## VERIFY — candidate verification & multi-hop pivot
    (candidate name + exactly ONE attribute, plain words)

    [V-001] :: ... (same 5-slot query shape as FIND)

    ## DECIDE — evidence check / anti-drift / stop & commit
    (DIRECTIVE bullets — decision rules, NOT search queries)

    [D-001] :: **Rule**: ...
             **Why**: ...
             **Apply when**: ...
             **Do NOT**: ...

Bullet IDs are ``<SLUG>-<NNN>`` with SLUG ∈ {F, V, D}. Multi-line bullet
content is accumulated until the next bullet / section / top header,
exactly like ``tactic_playbook``. The fixed
preamble lines under each header sit before the section's first bullet,
so the accumulator never attaches them to anything (they are dropped on
``from_text`` and regenerated by ``render()``).

Backward compatible parsing: an old ``tactic_playbook`` file (TACTIC_A /
TACTIC_B / TACTIC_C) loaded through this backend maps A and B → FIND and
C → VERIFY (see ``_normalize_section_name``), so ``init_from`` an old
playbook still works (A/B merge into the single FIND fingerprint stage,
as the redesign intends).
"""

from __future__ import annotations

import re
from dataclasses import replace
from typing import Any

from search_ttl.experience.base import Bullet, Experience, SectionInfo
from search_ttl.trainer.registry import register_experience

# Canonical key → (display title, slug, preamble lines). Order here is
# the on-disk / rendered section order. The ``desc`` lines are the
# agent-facing guidance — keep them dense-retriever-correct.
STAGES: dict[str, dict[str, Any]] = {
    "FIND": {
        "title": "FIND — anchored constraint fingerprint",
        "slug": "F",
        "desc": [
            "Use when NO candidate is known yet — locating the entity/document from clues.",
            "Query style: ONE coherent natural-language sentence; name the entity type "
            "(\"the novel\", \"the footballer\", \"the annual report\"); if a single rare "
            "token exists (proper noun / scientific name / exact title / unusual number) "
            "lead with it, else pack the 3-5 strongest constraints inline. The retriever "
            "is DENSE: keep names/dates/numbers as plain words IN the sentence — NO quotes, "
            "NO AND/OR, NO chain of quoted shards. Once any concrete candidate name "
            "appears, STOP and switch to VERIFY.",
        ],
    },
    "VERIFY": {
        "title": "VERIFY — candidate verification & multi-hop pivot",
        "slug": "V",
        "desc": [
            "Use AFTER a concrete candidate name or a bridge entity has appeared.",
            "Query style: candidate name + exactly ONE target attribute, plain words "
            "(no quotes / boolean). Verify clues ONE at a time. For a two-hop question "
            "(an attribute OF an entity you had to identify) pivot to "
            "`<identified entity> <the exact attribute asked for>`; do not re-run the "
            "original clue bundle.",
        ],
    },
    "DECIDE": {
        "title": "DECIDE — evidence check / anti-drift / stop & commit",
        "slug": "D",
        "desc": [
            "These are DECISION RULES, not search queries — apply them before answering.",
            "Each bullet is a directive (Rule / Why / Apply when / Do NOT). They cover: "
            "commit once the rarest constraints are met (stop re-verifying weak details); "
            "guard against drift to a more famous look-alike; always act and never "
            "finalize an empty answer; cross-check every explicit numeric/temporal "
            "constraint against the chosen source before finalizing.",
        ],
    },
}

_SECTION_ORDER: list[str] = list(STAGES)
_SLUG_TO_KEY: dict[str, str] = {v["slug"]: k for k, v in STAGES.items()}

# Bullet line: ``[F-001] :: content`` (uppercase slug, 1+ digits).
_BULLET_LINE = re.compile(r"^\[(?P<id>[A-Z]+-\d+)\]\s*::\s*(?P<content>.*)$")
_SECTION_LINE = re.compile(r"^##\s+(?P<name>.+?)\s*$")
_HEADER_LINE = re.compile(r"^#\s+.*$")


def _normalize_section_name(raw: str) -> str:
    """Map any section spelling the reflector/curator emits to one of
    the three canonical stage keys. Also maps the legacy ``tactic_playbook``
    spellings so ``init_from`` an old playbook keeps working:

      - TACTIC_A (exact anchor) / TACTIC_B (fingerprint) → FIND
        (the redesign merges anchor + fingerprint into one FIND stage)
      - TACTIC_C (candidate verification)               → VERIFY
      - anything decision/commit/evidence flavoured       → DECIDE

    Unknown → FIND (the most common discovery stage) so the playbook
    stays valid.
    """
    s = (raw or "").strip().lower()
    # DECIDE first — it is the newest and most specific intent.
    if (
        "decide" in s
        or "decision" in s
        or "commit" in s
        or "evidence" in s
        or "directive" in s
        or "anti-drift" in s
        or "stop" in s
        or s == "d"
    ):
        return "DECIDE"
    if (
        "verify" in s
        or "verification" in s
        or "candidate" in s
        or "pivot" in s
        or "tactic_c" in s
        or "tactic c" in s
        or s in ("v", "c")
    ):
        return "VERIFY"
    if (
        "find" in s
        or "fingerprint" in s
        or "anchor" in s
        or "discover" in s
        or "tactic_a" in s
        or "tactic a" in s
        or "tactic_b" in s
        or "tactic b" in s
        or s in ("f", "a", "b")
    ):
        return "FIND"
    return "FIND"


@register_experience("staged_playbook")
class StagedPlaybook(Experience):
    def __init__(
        self,
        bullets: dict[str, list[Bullet]],
        header: str = "# Search Agent Experience",
        next_id_per_slug: dict[str, int] | None = None,
    ) -> None:
        self._bullets: dict[str, list[Bullet]] = {
            sec: list(bullets.get(sec, [])) for sec in _SECTION_ORDER
        }
        self._header = header
        # Monotone id allocation per slug, even after deletes.
        self._next_id: dict[str, int] = dict(next_id_per_slug or {})
        for sec, bs in self._bullets.items():
            for b in bs:
                m = re.match(r"^([A-Za-z]+)-(\d+)$", b.bullet_id)
                if m:
                    slug = m.group(1)
                    self._next_id[slug] = max(
                        self._next_id.get(slug, 1), int(m.group(2)) + 1
                    )

    # ── construction ──────────────────────────────────────────────────────
    @classmethod
    def from_omegaconf(cls, cfg) -> "StagedPlaybook":
        # Sections are FIXED — cfg.sections is ignored by design. Only
        # ``init_from`` is honored (seed from an existing playbook file).
        init_from = cfg.get("init_from", None) if cfg is not None else None
        if init_from:
            from pathlib import Path

            text = Path(init_from).read_text(encoding="utf-8")
            return cls.from_text(text, cfg=cfg)
        return cls(bullets={sec: [] for sec in _SECTION_ORDER})

    @classmethod
    def from_text(cls, text: str, *, cfg=None) -> "StagedPlaybook":
        bullets: dict[str, list[Bullet]] = {sec: [] for sec in _SECTION_ORDER}
        header = "# Search Agent Experience"
        cur_section: str | None = None

        pending_id: str | None = None
        pending_section: str | None = None
        pending_lines: list[str] = []

        def _flush() -> None:
            nonlocal pending_id, pending_section, pending_lines
            if pending_id is not None and pending_section is not None:
                bullets.setdefault(pending_section, [])
                bullets[pending_section].append(
                    Bullet(
                        bullet_id=pending_id,
                        section=pending_section,
                        content="\n".join(pending_lines).strip(),
                        metadata={},
                    )
                )
            pending_id = None
            pending_section = None
            pending_lines = []

        for raw_line in text.splitlines():
            line = raw_line.rstrip()
            if _HEADER_LINE.match(line) and not _SECTION_LINE.match(line):
                _flush()
                header = line
                continue
            sm = _SECTION_LINE.match(line)
            if sm:
                _flush()
                cur_section = _normalize_section_name(sm.group("name"))
                continue
            bm = _BULLET_LINE.match(line.strip())
            if bm and cur_section is not None:
                _flush()
                pending_id = bm.group("id")
                pending_section = cur_section
                pending_lines = [bm.group("content")]
                continue
            # Continuation line of the open bullet. Preamble lines (the
            # fixed desc under a header, or the "(empty …)" placeholder)
            # are ignored because ``pending_id`` is still None there.
            if pending_id is not None:
                pending_lines.append(raw_line.rstrip())

        _flush()
        return cls(bullets=bullets, header=header)

    # ── read ──────────────────────────────────────────────────────────────
    def render(self) -> str:
        body: list[str] = [self._header, ""]
        for sec in _SECTION_ORDER:
            spec = STAGES[sec]
            body.append(f"## {spec['title']}")
            body.extend(spec["desc"])
            body.append("")
            bs = self._bullets.get(sec, [])
            if not bs:
                body.append("(empty — to be populated)")
            else:
                for b in bs:
                    body.append(f"[{b.bullet_id}] :: {b.content}")
            body.append("")
        return "\n".join(body).rstrip() + "\n"

    def to_text(self) -> str:
        return self.render()

    def list_sections(self) -> list[SectionInfo]:
        out: list[SectionInfo] = []
        for sec in _SECTION_ORDER:
            bs = self._bullets.get(sec, [])
            chars = sum(len(b.content) for b in bs)
            out.append(
                SectionInfo(name=sec, bullet_count=len(bs), char_count=chars)
            )
        return out

    def read_section(self, section: str) -> list[Bullet]:
        return list(self._bullets.get(_normalize_section_name(section), []))

    def read_bullet(self, bullet_id: str) -> Bullet | None:
        for bs in self._bullets.values():
            for b in bs:
                if b.bullet_id == bullet_id:
                    return b
        return None

    def search_bullets(self, keyword: str, top_k: int = 5) -> list[Bullet]:
        kw = keyword.lower().strip()
        if not kw:
            return []
        toks = _tokenize(kw)
        scored: list[tuple[int, Bullet]] = []
        for bs in self._bullets.values():
            for b in bs:
                content_toks = _tokenize(b.content.lower())
                hits = sum(1 for t in toks if t in content_toks)
                if hits:
                    scored.append((hits, b))
        scored.sort(key=lambda p: p[0], reverse=True)
        return [b for _, b in scored[:top_k]]

    def char_count(self) -> int:
        return len(self.render())

    # ── write (returns NEW instance — Experience is value-typed) ──────────
    def add_bullet(
        self, section: str, content: str, *, metadata: dict[str, Any] | None = None
    ) -> tuple["StagedPlaybook", Bullet]:
        sec = _normalize_section_name(section)
        slug = STAGES[sec]["slug"]
        next_n = self._next_id.get(slug, 1)
        bullet = Bullet(
            bullet_id=f"{slug}-{next_n:03d}",
            section=sec,
            content=content.strip(),
            metadata=dict(metadata or {}),
        )
        new = self._copy()
        new._bullets[sec] = list(new._bullets[sec]) + [bullet]
        new._next_id[slug] = next_n + 1
        return new, bullet

    def modify_bullet(
        self,
        bullet_id: str,
        new_content: str,
        *,
        metadata_patch: dict[str, Any] | None = None,
    ) -> tuple["StagedPlaybook", Bullet | None]:
        new = self._copy()
        for sec, bs in new._bullets.items():
            for i, b in enumerate(bs):
                if b.bullet_id == bullet_id:
                    merged = dict(b.metadata)
                    if metadata_patch:
                        merged.update(metadata_patch)
                    updated = replace(
                        b, content=new_content.strip(), metadata=merged
                    )
                    bs[i] = updated
                    return new, updated
        return new, None

    def delete_bullet(
        self, bullet_id: str, *, reason: str = ""
    ) -> tuple["StagedPlaybook", bool]:
        new = self._copy()
        for sec, bs in new._bullets.items():
            for i, b in enumerate(bs):
                if b.bullet_id == bullet_id:
                    bs.pop(i)
                    return new, True
        return new, False

    # ── internal ──────────────────────────────────────────────────────────
    def _copy(self) -> "StagedPlaybook":
        return StagedPlaybook(
            bullets={s: list(bs) for s, bs in self._bullets.items()},
            header=self._header,
            next_id_per_slug=dict(self._next_id),
        )


def _tokenize(s: str) -> list[str]:
    return [t for t in re.split(r"[^a-zA-Z0-9]+", s.lower()) if t]
