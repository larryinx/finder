"""TacticPlaybook — a 3-tactic Experience backend.

This playbook has exactly THREE fixed sections, one per search tactic,
each rendered with its title and a
two-line "when to use / query style" preamble:

    ## Tactic A: exact anchor probe
    Use for rare phrases, titles, exact numbers, document names.
    Query style: short, quoted, high precision.

    [A-001] :: <bullet content>

    ## Tactic B: constraint fingerprint query
    Use when no single clue is distinctive.
    Query style: combine 3-5 strongest constraints, not all clues.

    [B-001] :: ...

    ## Tactic C: candidate verification query
    Use after candidate appears.
    Query style: candidate name + one target attribute.

    [C-001] :: ...

Bullet IDs are ``<SLUG>-<NNN>`` — a single uppercase tactic letter plus
a 3-digit zero-padded counter (``A-001``, ``B-007``, ``C-012``).

Bullet content may span multiple physical lines (the rich structured
format the ``react_tactic`` curator writes); the parser accumulates
continuation lines until the next bullet / section / header. The fixed
two description
lines under each tactic header are regenerated by ``render()`` and
ignored by ``from_text`` (they sit before the section's first bullet,
so the accumulator never attaches them to anything).
"""

from __future__ import annotations

import re
from dataclasses import replace
from typing import Any

from search_ttl.experience.base import Bullet, Experience, SectionInfo
from search_ttl.trainer.registry import register_experience

# Canonical key → (display title, slug, two-line preamble). Order here
# is the on-disk / rendered section order.
TACTICS: dict[str, dict[str, Any]] = {
    "TACTIC_A": {
        "title": "Tactic A: exact anchor probe",
        "slug": "A",
        "desc": [
            "Use for rare phrases, titles, exact numbers, document names.",
            "Query style: short, quoted, high precision.",
        ],
    },
    "TACTIC_B": {
        "title": "Tactic B: constraint fingerprint query",
        "slug": "B",
        "desc": [
            "Use when no single clue is distinctive.",
            "Query style: combine 3-5 strongest constraints, not all clues.",
        ],
    },
    "TACTIC_C": {
        "title": "Tactic C: candidate verification query",
        "slug": "C",
        "desc": [
            "Use after candidate appears.",
            "Query style: candidate name + one target attribute.",
        ],
    },
}

_SECTION_ORDER: list[str] = list(TACTICS)
_SLUG_TO_KEY: dict[str, str] = {v["slug"]: k for k, v in TACTICS.items()}

# Bullet line: ``[A-001] :: content``  (uppercase slug, 3+ digits).
_BULLET_LINE = re.compile(
    r"^\[(?P<id>[A-Z]+-\d+)\]\s*::\s*(?P<content>.*)$"
)
_SECTION_LINE = re.compile(r"^##\s+(?P<name>.+?)\s*$")
_HEADER_LINE = re.compile(r"^#\s+.*$")


def _normalize_section_name(raw: str) -> str:
    """Map any free-form section spelling the curator/reflector emits
    to one of the three canonical tactic keys. Unknown → TACTIC_B (the
    most general fingerprint tactic) so the playbook stays valid.
    """
    s = (raw or "").strip().lower()
    if "tactic_a" in s or "tactic a" in s or "exact anchor" in s or s == "a":
        return "TACTIC_A"
    if (
        "tactic_c" in s
        or "tactic c" in s
        or "candidate verification" in s
        or s == "c"
    ):
        return "TACTIC_C"
    if (
        "tactic_b" in s
        or "tactic b" in s
        or "constraint fingerprint" in s
        or s == "b"
    ):
        return "TACTIC_B"
    return "TACTIC_B"


@register_experience("tactic_playbook")
class TacticPlaybook(Experience):
    def __init__(
        self,
        bullets: dict[str, list[Bullet]],
        header: str = "# Search Agent Experience",
        next_id_per_slug: dict[str, int] | None = None,
    ) -> None:
        self._bullets: dict[str, list[Bullet]] = {
            sec: list(bullets.get(sec, [])) for sec in _SECTION_ORDER
        }
        self._header = header
        # Monotone id allocation per slug, even after deletes.
        self._next_id: dict[str, int] = dict(next_id_per_slug or {})
        for sec, bs in self._bullets.items():
            for b in bs:
                m = re.match(r"^([A-Za-z]+)-(\d+)$", b.bullet_id)
                if m:
                    slug = m.group(1)
                    self._next_id[slug] = max(
                        self._next_id.get(slug, 1), int(m.group(2)) + 1
                    )

    # ── construction ──────────────────────────────────────────────────────
    @classmethod
    def from_omegaconf(cls, cfg) -> "TacticPlaybook":
        # Sections are FIXED for a tactic playbook — cfg.sections is
        # ignored by design. Only ``init_from`` is honored.
        init_from = cfg.get("init_from", None) if cfg is not None else None
        if init_from:
            from pathlib import Path

            text = Path(init_from).read_text(encoding="utf-8")
            return cls.from_text(text, cfg=cfg)
        return cls(bullets={sec: [] for sec in _SECTION_ORDER})

    @classmethod
    def from_text(cls, text: str, *, cfg=None) -> "TacticPlaybook":
        bullets: dict[str, list[Bullet]] = {sec: [] for sec in _SECTION_ORDER}
        header = "# Search Agent Experience"
        cur_section: str | None = None

        # Multi-line bullet accumulator: a bullet's content may span several
        # physical lines; keep an "open" bullet and append continuation
        # lines until the next bullet line / section / top-level header.
        pending_id: str | None = None
        pending_section: str | None = None
        pending_lines: list[str] = []

        def _flush() -> None:
            nonlocal pending_id, pending_section, pending_lines
            if pending_id is not None and pending_section is not None:
                bullets.setdefault(pending_section, [])
                bullets[pending_section].append(
                    Bullet(
                        bullet_id=pending_id,
                        section=pending_section,
                        content="\n".join(pending_lines).strip(),
                        metadata={},
                    )
                )
            pending_id = None
            pending_section = None
            pending_lines = []

        for raw_line in text.splitlines():
            line = raw_line.rstrip()
            if _HEADER_LINE.match(line) and not _SECTION_LINE.match(line):
                _flush()
                header = line
                continue
            sm = _SECTION_LINE.match(line)
            if sm:
                _flush()
                cur_section = _normalize_section_name(sm.group("name"))
                continue
            bm = _BULLET_LINE.match(line.strip())
            if bm and cur_section is not None:
                _flush()
                pending_id = bm.group("id")
                pending_section = cur_section
                pending_lines = [bm.group("content")]
                continue
            # Continuation line of the open bullet. Lines before any
            # bullet has opened (the fixed two description lines under a
            # tactic header, or the "(empty …)" placeholder) are ignored
            # because ``pending_id`` is still None there.
            if pending_id is not None:
                pending_lines.append(raw_line.rstrip())

        _flush()
        return cls(bullets=bullets, header=header)

    # ── read ──────────────────────────────────────────────────────────────
    def render(self) -> str:
        empty = all(not bs for bs in self._bullets.values())
        body: list[str] = [self._header, ""]
        for sec in _SECTION_ORDER:
            spec = TACTICS[sec]
            body.append(f"## {spec['title']}")
            body.extend(spec["desc"])
            body.append("")
            bs = self._bullets.get(sec, [])
            if not bs:
                body.append("(empty — to be populated)")
            else:
                for b in bs:
                    body.append(f"[{b.bullet_id}] :: {b.content}")
            body.append("")
        out = "\n".join(body).rstrip() + "\n"
        return out if not empty else out  # same shape either way

    def to_text(self) -> str:
        return self.render()

    def list_sections(self) -> list[SectionInfo]:
        out: list[SectionInfo] = []
        for sec in _SECTION_ORDER:
            bs = self._bullets.get(sec, [])
            chars = sum(len(b.content) for b in bs)
            out.append(
                SectionInfo(name=sec, bullet_count=len(bs), char_count=chars)
            )
        return out

    def read_section(self, section: str) -> list[Bullet]:
        return list(self._bullets.get(_normalize_section_name(section), []))

    def read_bullet(self, bullet_id: str) -> Bullet | None:
        for bs in self._bullets.values():
            for b in bs:
                if b.bullet_id == bullet_id:
                    return b
        return None

    def search_bullets(self, keyword: str, top_k: int = 5) -> list[Bullet]:
        kw = keyword.lower().strip()
        if not kw:
            return []
        toks = _tokenize(kw)
        scored: list[tuple[int, Bullet]] = []
        for bs in self._bullets.values():
            for b in bs:
                content_toks = _tokenize(b.content.lower())
                hits = sum(1 for t in toks if t in content_toks)
                if hits:
                    scored.append((hits, b))
        scored.sort(key=lambda p: p[0], reverse=True)
        return [b for _, b in scored[:top_k]]

    def char_count(self) -> int:
        return len(self.render())

    # ── write (returns NEW instance — Experience is value-typed) ──────────
    def add_bullet(
        self, section: str, content: str, *, metadata: dict[str, Any] | None = None
    ) -> tuple["TacticPlaybook", Bullet]:
        sec = _normalize_section_name(section)
        slug = TACTICS[sec]["slug"]
        next_n = self._next_id.get(slug, 1)
        bullet = Bullet(
            bullet_id=f"{slug}-{next_n:03d}",
            section=sec,
            content=content.strip(),
            metadata=dict(metadata or {}),
        )
        new = self._copy()
        new._bullets[sec] = list(new._bullets[sec]) + [bullet]
        new._next_id[slug] = next_n + 1
        return new, bullet

    def modify_bullet(
        self,
        bullet_id: str,
        new_content: str,
        *,
        metadata_patch: dict[str, Any] | None = None,
    ) -> tuple["TacticPlaybook", Bullet | None]:
        new = self._copy()
        for sec, bs in new._bullets.items():
            for i, b in enumerate(bs):
                if b.bullet_id == bullet_id:
                    merged = dict(b.metadata)
                    if metadata_patch:
                        merged.update(metadata_patch)
                    updated = replace(
                        b, content=new_content.strip(), metadata=merged
                    )
                    bs[i] = updated
                    return new, updated
        return new, None

    def delete_bullet(
        self, bullet_id: str, *, reason: str = ""
    ) -> tuple["TacticPlaybook", bool]:
        new = self._copy()
        for sec, bs in new._bullets.items():
            for i, b in enumerate(bs):
                if b.bullet_id == bullet_id:
                    bs.pop(i)
                    return new, True
        return new, False

    # ── internal ──────────────────────────────────────────────────────────
    def _copy(self) -> "TacticPlaybook":
        return TacticPlaybook(
            bullets={s: list(bs) for s, bs in self._bullets.items()},
            header=self._header,
            next_id_per_slug=dict(self._next_id),
        )


def _tokenize(s: str) -> list[str]:
    return [t for t in re.split(r"[^a-zA-Z0-9]+", s.lower()) if t]
